import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('./', import.meta.url);
const read = name => readFile(new URL(name, root), 'utf8');
const write = (name, content) => writeFile(new URL(name, root), content);
const { name, version } = JSON.parse(await read('package.json'));
const css = await read('theme.css');
const palette = JSON.parse(await read('palette.json'));
const client = await read('client-source.js');
const highlight = await read('highlight-source.js');
const composer = await read('composer-source.js');
const vendor = await read('vendor/package/highlight.min.js');
const parser = `    function createFallbackParser(exports, module) {\n${vendor}\n      return hljs;\n    }`;

await mkdir(new URL('lib/', root), { recursive: true });
await write('lib/index.js', `'use strict';\nexports.apply = () => {};\n`);
await write('lib/client.js', `// Generated by node build.mjs.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(name)},\n  factory: () => {\n    'use strict';\n    const id = ${JSON.stringify(name)};\n    const version = ${JSON.stringify(version)};\n    const css = ${JSON.stringify(css)};\n    const palette = ${JSON.stringify(palette)};\n${parser}\n${highlight}\n${composer}\n${client}\n    return { apply, inject: ['theme'] };\n  },\n});\n`);
